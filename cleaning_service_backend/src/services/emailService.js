// src/services/emailService.js
const nodemailer = require('nodemailer');
require('dotenv').config();

// Transporter එක හදාගැනීම (Gmail සඳහා)
// src/services/emailService.js හි වෙනස් විය යුතු කොටස

const transporter = nodemailer.createTransport({
    host: 'smtp.gmail.com',
    port: 587,
    secure: false, // Port 587 සඳහා මෙය false විය යුතුය
    auth: {
        user: process.env.EMAIL_USER,
        pass: process.env.EMAIL_PASS
    },
    tls: {
        rejectUnauthorized: false // Local development වලදී එන SSL errors මඟහරවා ගැනීමට
    }
});

/**
 * Customer ට සහ Admin ට PDF එකත් එක්ක Email එක යවන Function එක
 */
exports.sendReportEmail = async (customerEmail, pdfBuffer, jobDetails = {}) => {
    try {
        const adminEmail = process.env.ADMIN_EMAIL || process.env.EMAIL_USER;
        const customerName = jobDetails.name || 'Valued Customer';
        const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });

        // Email recipients (Customer and Admin)
        const recipients = [customerEmail];
        let ccList = [];
        if (adminEmail && adminEmail.toLowerCase() !== (customerEmail || '').toLowerCase()) {
            ccList.push(adminEmail);
        }

        const mailOptions = {
            from: `"JaniFlow Operations" <${process.env.EMAIL_USER}>`,
            to: recipients.join(', '),
            cc: ccList.length > 0 ? ccList.join(', ') : undefined,
            subject: `JaniFlow Inspection Report - ${customerName} (${dateStr})`,
            html: `
                <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #e0e0e0; border-radius: 8px;">
                    <div style="background-color: #1e3a8a; color: #ffffff; padding: 16px; border-radius: 6px; text-align: center;">
                        <h2 style="margin: 0; letter-spacing: 0.5px;">JaniFlow</h2>
                        <p style="margin: 4px 0 0 0; font-size: 13px; opacity: 0.9;">Professional Cleaning & Inspection Report</p>
                    </div>
                    <div style="padding: 20px 10px; color: #333333; line-height: 1.6;">
                        <p>Dear <strong>${customerName}</strong>,</p>
                        <p>We are pleased to inform you that the assigned cleaning visit has been successfully completed at your property.</p>
                        <p>A detailed inspection checklist and photo proof report has been generated by our staff and attached to this email as a PDF document for your records.</p>
                        <div style="background-color: #f3f4f6; padding: 12px; border-radius: 6px; margin: 15px 0;">
                            <strong>Summary Details:</strong>
                            <ul style="margin: 5px 0 0 0; padding-left: 20px;">
                                <li>Customer: ${customerName}</li>
                                <li>Address: ${jobDetails.address || 'On file'}</li>
                                <li>Date: ${dateStr}</li>
                            </ul>
                        </div>
                        <p>If you have any feedback or inquiries, please feel free to reach out to our operations team.</p>
                        <p style="margin-top: 25px;">Warm regards,<br><strong>JaniFlow Operations Team</strong></p>
                    </div>
                    <div style="text-align: center; color: #888888; font-size: 12px; border-top: 1px solid #eeeeee; padding-top: 10px;">
                        This is an automated report notification sent via JaniFlow System.
                    </div>
                </div>
            `,
            text: `Dear ${customerName},\n\nYour cleaning inspection has been completed on ${dateStr}. Please find your JaniFlow service report and photo proof attached.\n\nThank you,\nJaniFlow Operations Team`,
            attachments: [
                {
                    filename: `JaniFlow_Report_${customerName.replace(/\s+/g, '_')}_${Date.now()}.pdf`,
                    content: pdfBuffer,
                    contentType: 'application/pdf'
                }
            ]
        };

        const info = await transporter.sendMail(mailOptions);
        console.log('✅ Email sent successfully to customer and admin: ' + info.response);
        return info;
    } catch (error) {
        console.error('❌ Error sending email:', error);
        throw error;
    }
};